/** The full week list, in the same shape the page has always used. Built once per request. */
var RW_WEEKS_CACHE_ = null;
function rwWeeks_() {
  if (RW_WEEKS_CACHE_) return RW_WEEKS_CACHE_;
  RW_WEEKS_CACHE_ = RW_RAW.map(function (weekDays, wi) {
    var n = wi + 1, id = 'w' + n;
    return {
      id: id, num: n, label: 'Week ' + n, subtitle: 'Word Within the Word — List #' + n,
      days: weekDays.map(function (lines, di) {
        var plan = RW_DAY_PLAN[di];
        return {
          day: plan.day, label: plan.label, accent: plan.accent,
          roots: lines.map(function (line) {
            var p = line.split('|');
            var r = {
              root: p[0], display: p[0].toUpperCase(), meaning: p[1], origin: p[2],
              examples: p[3].split(';'), variants: [p[0].toLowerCase()]
            };
            var override = RW_KEY_OVERRIDES[id + '|' + plan.day + '|' + p[0]];
            if (override) r.key = override;
            return r;
          })
        };
      })
    };
  });
  return RW_WEEKS_CACHE_;
}
function rwRootKey_(r) { return r.key || r.root; }
function rwWeekById_(weekId) {
  var w = rwWeeks_().filter(function (x) { return x.id === String(weekId); })[0];
  if (!w) throw new Error('Unknown week.');
  return w;
}
function rwAllRoots_(week) {
  var out = [];
  week.days.forEach(function (d) { d.roots.forEach(function (r) { var c = JSON.parse(JSON.stringify(r)); c.day = d.day; out.push(c); }); });
  return out;
}
